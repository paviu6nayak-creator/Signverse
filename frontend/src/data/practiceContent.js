/**
 * Filter items by difficulty level.
 * @param {PracticeLevel | 'all'} level
 * @returns {PracticeItem[]}
 */
export function getPracticeItemsByLevel(level = "all") {
  if (level === "all") return PRACTICE_ITEMS;
  return PRACTICE_ITEMS.filter((item) => item.level === level);
}

/**
 * Filter items by practice type ('letter' | 'word' | 'phrase' | 'sentence').
 * @param {PracticeItemType} type
 * @returns {PracticeItem[]}
 */
export function getPracticeItemsByType(type) {
  return PRACTICE_ITEMS.filter((item) => item.type === type);
}

/**
 * Find a practice item by ID or sign key.
 * @param {string} key
 * @returns {PracticeItem | undefined}
 */
export function findPracticeItem(key) {
  if (!key) return undefined;
  const normalized = key.toLowerCase().trim();
  return PRACTICE_ITEMS.find(
    (item) =>
      item.id.toLowerCase() === normalized ||
      item.label.toLowerCase() === normalized ||
      item.id.replace(/^(letter|word|sentence)-/, "").toLowerCase() === normalized
  );
}
